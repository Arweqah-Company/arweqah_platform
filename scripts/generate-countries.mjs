// Shown first in selects: Saudi Arabia, the Gulf, Egypt.
const FIRST = ['SA', 'AE', 'KW', 'QA', 'BH', 'OM', 'EG'];

const regionAr = new Intl.DisplayNames(['ar'], { type: 'region' });
const regionEn = new Intl.DisplayNames(['en'], { type: 'region' });
const currencyAr = new Intl.DisplayNames(['ar'], { type: 'currency' });
const currencyEn = new Intl.DisplayNames(['en'], { type: 'currency' });

const rows = CURRENCY_BY_COUNTRY.split(',').map((pair) => pair.trim().split(' ')).filter((p) => p.length === 2);
const countries = rows.map(([iso, currency]) => ({
  iso,
  currency,
  nameAr: regionAr.of(iso),
  nameEn: regionEn.of(iso),
  currencyNameAr: currencyAr.of(currency),
  currencyNameEn: currencyEn.of(currency),
}));

const bad = countries.filter((c) => !c.nameAr || c.nameAr === c.iso || !c.nameEn || c.nameEn === c.iso || !c.currencyNameAr || c.currencyNameAr === c.currency);
if (bad.length) console.warn('Check names for:', bad.map((c) => c.iso).join(', '));

countries.sort((a, b) => {
  const fa = FIRST.indexOf(a.iso);
  const fb = FIRST.indexOf(b.iso);
  if (fa !== -1 || fb !== -1) return (fa === -1 ? 99 : fa) - (fb === -1 ? 99 : fb);
  return a.nameEn.localeCompare(b.nameEn, 'en');
});

const lines = countries.map((c) => `  ${JSON.stringify(c)},`).join('\n');
const out = `// Generated by scripts/generate-countries.mjs. Do not edit by hand.
export interface CountrySeed {
  iso: string;
  currency: string;
  nameAr: string;
  nameEn: string;
  currencyNameAr: string;
  currencyNameEn: string;
}

export const COUNTRIES: CountrySeed[] = [
${lines}
];
`;
writeFileSync(fileURLToPath(new URL('../apps/api/src/database/seeds/data/countries.data.ts', import.meta.url)), out);
console.log(`Wrote ${countries.length} countries`);
